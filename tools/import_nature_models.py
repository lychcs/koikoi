#!/usr/bin/env python3
"""Import the curated nature models from "Ultimate Stylized Nature - May 2022".

The source pack ships huge 2048px bark sheets and MTL files without any
``map_Kd`` links.  This script copies only the models used by the overworld,
downsamples their textures to a pixel-art friendly 512px, recolors the foliage
into the game's Mokuhanga palette and writes self-contained MTL files.

Run from the repository root:

    python tools/import_nature_models.py

The generated files live in ``assets/models/nature`` and are committed; the
raw pack itself is ignored by git.
"""

from __future__ import annotations

import shutil
from pathlib import Path
from typing import Dict, Tuple

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Ultimate Stylized Nature - May 2022" / "OBJ"
SOURCE_TEXTURES = ROOT / "Ultimate Stylized Nature - May 2022" / "Textures"
TARGET = ROOT / "assets" / "models" / "nature"
TEXTURE_SIZE = 512

# Curated low-poly set.  Every source OBJ has its pivot at the root (y ~ 0).
MODELS = (
    "MapleTree_4",
    "PineTree_1",
    "PineTree_3",
    "Rock_1",
    "Rock_3",
    "Bush_Small",
    "Bush_Large",
    "Grass_Small",
    "Grass_Large_Extruded",
    "Flower_1_Clump",
)

# texture -> (output name, colorize dark, colorize light, keep original colors)
# ``colorize`` maps the source luminance onto a two-color ramp while preserving
# the alpha cutout; trees/bushes become sakura, pines stay mossy evergreen.
TEXTURES: Dict[str, Tuple[str, Tuple[float, float, float],
                           Tuple[float, float, float], bool]] = {
    "MapleTree_Bark.png": ("MapleTree_Bark.png", (0, 0, 0), (0, 0, 0), True),
    "MapleTree_Leaves.png": (
        "MapleTree_Leaves.png", (0.180, 0.070, 0.120), (0.980, 0.650, 0.735), False),
    "PineTree_Bark.png": ("PineTree_Bark.png", (0, 0, 0), (0, 0, 0), True),
    "PineTree_Leaves.png": (
        "PineTree_Leaves.png", (0.055, 0.135, 0.100), (0.370, 0.560, 0.370), False),
    "Bush_Leaves.png": (
        "Bush_Leaves.png", (0.210, 0.090, 0.180), (0.930, 0.570, 0.670), False),
    "Grass.png": (
        "Grass.png", (0.090, 0.165, 0.075), (0.490, 0.650, 0.275), False),
    "Flowers.png": ("Flowers.png", (0, 0, 0), (0, 0, 0), True),
    "Rocks.png": ("Rocks.png", (0, 0, 0), (0, 0, 0), True),
}

# Material name -> (texture, diffuse tint).  White Kd lets the painted texture
# carry the color; the shader applies the tint on top.
MATERIALS = {
    "MapleTree_Bark": ("MapleTree_Bark.png", (0.78, 0.62, 0.52)),
    "MapleTree_Leaves": ("MapleTree_Leaves.png", (1.00, 0.93, 0.95)),
    "PineTree_Bark": ("PineTree_Bark.png", (0.72, 0.62, 0.52)),
    "PineTree_Leaves": ("PineTree_Leaves.png", (0.92, 1.00, 0.92)),
    "Bush_Leaves": ("Bush_Leaves.png", (1.00, 0.92, 0.95)),
    "Grass": ("Grass.png", (0.92, 1.00, 0.88)),
    "Flowers": ("Flowers.png", (1.00, 0.92, 0.95)),
    "Rock": ("Rocks.png", (0.86, 0.91, 0.94)),
}


def colorize(image: Image.Image, dark, light) -> Image.Image:
    """Map luminance onto a flat two-color woodblock ramp, keeping alpha."""
    rgba = image.convert("RGBA")
    pixels = []
    for red, green, blue, alpha in rgba.getdata():
        # Perceptual luminance; alpha zero texels are discarded by the shader.
        value = (0.299 * red + 0.587 * green + 0.114 * blue) / 255.0
        # Slight S-curve keeps leaf veins readable after the flat color ramp.
        value = min(1.0, max(0.0, (value - 0.18) / 0.72))
        value = value * value * (3.0 - 2.0 * value)
        pixels.append((
            round((dark[0] + (light[0] - dark[0]) * value) * 255),
            round((dark[1] + (light[1] - dark[1]) * value) * 255),
            round((dark[2] + (light[2] - dark[2]) * value) * 255),
            alpha,
        ))
    rgba.putdata(pixels)
    return rgba


def import_textures() -> None:
    output = TARGET / "textures"
    output.mkdir(parents=True, exist_ok=True)
    for source_name, (target_name, dark, light, keep) in TEXTURES.items():
        image = Image.open(SOURCE_TEXTURES / source_name).convert("RGBA")
        image = image.resize((TEXTURE_SIZE, TEXTURE_SIZE), Image.Resampling.LANCZOS)
        if not keep:
            image = colorize(image, dark, light)
        image.save(output / target_name, optimize=True)


def write_mtl(path: Path, materials) -> None:
    lines = [
        "# Imported from Ultimate Stylized Nature - May 2022.",
        "# Generated by tools/import_nature_models.py; do not edit by hand.",
        "",
    ]
    for material in sorted(materials):
        texture, tint = MATERIALS[material]
        lines.extend([
            f"newmtl {material}",
            "Ka 1.000000 1.000000 1.000000",
            "Kd {:.6f} {:.6f} {:.6f}".format(*tint),
            "Ks 0.000000 0.000000 0.000000",
            "Ke 0.000000 0.000000 0.000000",
            "Ni 1.000000",
            "d 1.000000",
            "illum 1",
            f"map_Kd textures/{texture}",
            "",
        ])
    path.write_text("\n".join(lines), encoding="utf-8")


def import_models() -> None:
    TARGET.mkdir(parents=True, exist_ok=True)
    for name in MODELS:
        obj = SOURCE / f"{name}.obj"
        text = obj.read_text(encoding="utf-8", errors="ignore")
        materials = {
            line.split(None, 1)[1].strip()
            for line in text.splitlines()
            if line.startswith("usemtl ")
        }
        unknown = materials - MATERIALS.keys()
        if unknown:
            raise SystemExit(f"{name}: unmapped materials {sorted(unknown)}")

        shutil.copyfile(obj, TARGET / obj.name)
        write_mtl(TARGET / f"{name}.mtl", materials)
        print(f"imported {name}: {len(materials)} material(s)")


def main() -> None:
    if not SOURCE.is_dir():
        raise SystemExit(f"source pack not found: {SOURCE}")
    import_textures()
    import_models()
    print(f"nature assets written to {TARGET}")


if __name__ == "__main__":
    main()
